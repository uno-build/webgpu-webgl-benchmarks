export type EngineId = 'three' | 'playcanvas' | 'babylon' | 'babylon-lite' | 'three-classic';
export type Backend = 'webgpu' | 'webgl2';
export type Variant = 'naive' | 'optimized';
export type Mode = 'timing' | 'counters';
export type ScenarioId = 's0' | 's1' | 's2' | 's3' | 's4' | 's5' | 's6' | 's7' | 's8' | 's8b' | 's9';
export type RunTag = 'prime' | 'canary' | 'calibration';

export type Vec3 = [number, number, number];

/** Parameters of one benchmark run — one page load of bench.html. */
export interface RunParams {
  engine: EngineId | 'none';
  backend: Backend;
  scenario: ScenarioId | 'cal';
  variant: Variant;
  level: number;
  mode: Mode;
  repeat: number;
  warmupFrames: number;
  warmupMs: number;
  measureFrames: number;
  measureMs: number;
  /** Hard cap on the measure phase, so pathological levels still finish. */
  maxMeasureMs: number;
  screenshot: boolean;
  /** Keep rendering with a live overlay instead of reporting + navigating (manual debugging). */
  standalone: boolean;
  /** Inject timestamp queries for GPU time (disable where a browser's implementation is unstable). */
  gpuTiming: boolean;
  /** Force a specific optimized-path candidate (spike trials). */
  opt?: string;
  session?: string;
  runId?: string;
  tag?: RunTag;
}

export interface InitOptions {
  backend: Backend;
  width: number;
  height: number;
  msaa: 1 | 4;
}

export interface InitReport {
  /** Backend the engine actually ended up on — engines fall back silently. */
  backend: Backend;
  msaa: number;
  notes?: string[];
}

export interface LoadReport {
  /** Human-readable name of the rendering path used (e.g. "InstancedMesh per geometry"). */
  path: string;
  notes?: string[];
}

/**
 * Contract every engine implements. The harness owns the rAF loop; adapters never schedule frames.
 * All scene state must be a pure function of `t` (or of the sequence of `dt` steps from t=0),
 * so frame k is identical across engines and browsers.
 */
export interface EngineAdapter {
  readonly name: string;
  readonly version: string;
  init(canvas: HTMLCanvasElement, opts: InitOptions): Promise<InitReport>;
  /** Build the scene and finish pipeline compilation (engine precompile API + warm-up frames as needed). */
  load(scene: SceneData, variant: Variant, opt?: string): Promise<LoadReport>;
  /** Update + render exactly one frame, submitting GPU work before returning. */
  frame(t: number, dt: number): void;
  /** Engine-reported stats for the last frame, used to cross-check the probe. */
  counters?(): Record<string, number>;
  dispose(): Promise<void>;
}

// ---------------------------------------------------------------------------------------------
// Scene description shared by all engines. Everything is plain data generated by a seeded RNG.
// Colors are LINEAR. Coordinates are right-handed, Y-up, meters.
// ---------------------------------------------------------------------------------------------

export interface Geometry {
  name: string;
  positions: Float32Array;
  normals: Float32Array;
  uvs: Float32Array;
  indices: Uint16Array | Uint32Array;
}

export interface CameraSpec {
  position: Vec3;
  target: Vec3;
  /** Vertical field of view, degrees. */
  fovY: number;
  near: number;
  far: number;
}

export interface PbrSpec {
  color: Vec3;
  roughness: number;
  metalness: number;
}

export interface SunSpec {
  /** Direction the light travels (from the light towards the scene), normalized. */
  direction: Vec3;
  color: Vec3;
  /** Illuminance in spec units; adapters map it to engine units (see LIGHT_SCALE in each adapter). */
  intensity: number;
  shadow?: { cascades: number; mapSize: number; maxDistance: number };
}

export interface SpotSpec {
  position: Vec3;
  target: Vec3;
  color: Vec3;
  intensity: number;
  range: number;
  /** Half-angle of the cone, degrees. */
  angle: number;
  /** 0..1 fraction of the cone that is soft. */
  penumbra: number;
  shadowMapSize: number;
}

export interface PointLightsSpec {
  count: number;
  /** Live: xyz per light, rewritten by update(t). */
  position: Float32Array;
  /** Linear rgb per light. */
  color: Float32Array;
  intensity: number;
  range: number;
}

export interface PostSpec {
  bloom: { strength: number; threshold: number; radius: number };
}

interface BaseScene {
  camera: CameraSpec;
  clearColor: Vec3;
  ambient: { color: Vec3; intensity: number };
  sun?: SunSpec;
  /** Advance all live data to time t (seconds). Timed separately from engine work. */
  update(t: number): void;
}

/** S0, S1, S2, S4, S5, S6: many individual meshes (plus optional ground, lights, shadows, post). */
export interface FieldScene extends BaseScene {
  kind: 'field';
  geometries: Geometry[];
  materials: PbrSpec[];
  count: number;
  geom: Uint8Array;
  material: Uint16Array;
  position: Float32Array;
  scale: Float32Array;
  /** Live: xyzw per object, rewritten by update(t) when `animated`. */
  quat: Float32Array;
  animated: boolean;
  ground?: { size: number; material: PbrSpec };
  pointLights?: PointLightsSpec;
  spots?: SpotSpec[];
  post?: PostSpec;
  /** Objects/ground cast and receive shadows when the sun or spots have shadows. */
  shadows: boolean;
}

/** S3: one geometry, N instances, all matrices rewritten every frame. */
export interface InstancesScene extends BaseScene {
  kind: 'instances';
  geometry: Geometry;
  material: PbrSpec;
  count: number;
  /** Live: column-major 4x4 per instance (translation at 12..14), rewritten by update(t). */
  matrices: Float32Array;
}

/** S7: a static glTF scene with a scripted camera path (camera is live). */
export interface GltfScene extends BaseScene {
  kind: 'gltf-scene';
  url: string;
}

/** S8: N skinned characters playing a clip at per-character phase offsets. */
export interface CharactersScene extends BaseScene {
  kind: 'characters';
  url: string;
  count: number;
  /** Animation clip index to play. */
  clip: number;
  /** Uniform scale applied to each character root. */
  scale: number;
  /** xyz per character. */
  position: Float32Array;
  /** Yaw per character, radians. */
  yaw: Float32Array;
  /** Seconds added to t for each character's clip time. */
  phase: Float32Array;
}

/** S9: GPU particle simulation. Initial state is shared; the sim runs in each engine's compute API. */
export interface ParticlesScene extends BaseScene {
  kind: 'particles';
  count: number;
  /** xyzw per particle (w unused = 1). */
  initPosition: Float32Array;
  /** xyzw per particle (w unused = 0). */
  initVelocity: Float32Array;
  /** Half-extent of the bounding box particles bounce inside. */
  bounds: number;
  /** World-space size of each particle quad. */
  size: number;
  /** WGSL-equivalent reference of the per-step integration, documented for adapters. */
  sim: { attractorRadius: number; attractorSpeed: number; strength: number; damping: number };
}

export type SceneData = FieldScene | InstancesScene | GltfScene | CharactersScene | ParticlesScene;

/** Per-frame counters collected by the probes in counters mode (medians are reported). */
export type FrameCounters = Record<string, number>;
